"""Identical causal detector trajectory for training, validation and deployment."""

import time

import numpy as np
import torch

from benchmarks.stage_a.model import contrast_loss

from .detector import Detector
from .model import correct, waveform_loss


def duplicate_loss(sources):
    if sources.shape[1] < 2:
        return sources.sum() * 0
    x = sources - sources.mean(0)
    x = x / x.square().sum(0).clamp_min(1e-10).sqrt()
    correlation = x.T @ x
    off_diagonal = correlation - torch.diag_embed(correlation.diagonal())
    return off_diagonal.square().sum() / (sources.shape[1] * (sources.shape[1] - 1))


def replay(record, models, *, optimizer=None, collect=False):
    """Original Pareto SV/whitening branch is unmodified; head SD evolves here.

    Hard peak decisions and detector state are detached in BOTH training and
    deployment. Gradients flow through corrected sources to the shared gate.
    The cached Pareto sources were generated by its complete adaptive circuit.
    """
    started = time.perf_counter()
    config, calibration = record["config"], record["calibration"]
    detector = Detector(calibration, config)
    state = detector.decomp
    cal_spike = state.spikes_centr_cal.clamp_min(1e-7)
    cal_gap = (state.spikes_centr_cal - state.base_centr_cal).clamp_min(1e-7)
    scale = state.sources_calib.square().mean(0).sqrt().clamp_min(1e-5)
    predictions = np.zeros(record["base"].shape, dtype=np.uint8) if collect else None
    returned_sources = np.zeros(record["base"].shape, dtype=np.float32) if collect else None
    previous = torch.zeros(record["base"].shape[1])
    values, history, coefficients, components = [], [], [], []
    durations = []
    for index, start in enumerate(range(0, len(record["base"]), config.batch_size)):
        tick = time.perf_counter()
        stop = min(start + config.batch_size, len(record["base"]))
        trim = config.ext_fact if index == 0 else 0
        p, f = record["base"][start + trim : stop], record["frozen"][start + trim : stop]
        centroid_features = torch.stack(
            [
                (state.spikes_centr.clamp_min(1e-7) / cal_spike).log(),
                ((state.spikes_centr - state.base_centr).clamp_min(1e-7) / cal_gap).log(),
            ],
            -1,
        )
        features = torch.cat([record["features"][index], centroid_features], -1).detach()
        a = (
            torch.stack([model(features) for model in models]).mean(0)
            if models
            else torch.zeros_like(previous)
        )
        if start < 5 * config.fs:
            a = a * 0  # Keep supervised initial calibration unchanged.
        sources = correct(p, f, a)
        spikes, trusted = detector.step(sources, index)
        if collect:
            predictions[start + trim : stop] = spikes.numpy().astype(np.uint8)
            returned_sources[start + trim : stop] = sources.detach().numpy()
        if start >= 5 * config.fs and index % 4 == 0:
            ctr = contrast_loss(
                sources, trusted.float(), state.contrast_calib_mean, state.contrast_calib_std
            )
            shape = waveform_loss(sources, trusted, record["template"])
            duplicates = duplicate_loss(sources)
            anchor = ((sources - p) / scale).square().mean()
            size = (a / 0.15).square().mean()
            smooth = ((a - previous) / 0.15).square().mean()
            loss = 0.1 * ctr + shape + 0.2 * duplicates + 0.1 * anchor + 0.02 * size + 0.01 * smooth
            if not torch.isfinite(loss):
                raise FloatingPointError("Non-finite residual objective")
            values.append(loss)
            components.append([float(x.detach()) for x in (ctr, shape, duplicates, anchor, size)])
        coefficients.append(float(a.detach().abs().mean()))
        previous = a
        if (index + 1) % 32 == 0 or stop == len(record["base"]):
            if values:
                objective = torch.stack(values).mean()
                history.extend(float(x.detach()) for x in values)
                if optimizer is not None:
                    optimizer.zero_grad()
                    objective.backward()
                    torch.nn.utils.clip_grad_norm_(models[0].parameters(), 1.0)
                    optimizer.step()
                values = []
            previous = previous.detach()
        durations.append((time.perf_counter() - tick) * 1000)
    return dict(
        objective=float(np.mean(history)),
        contrast=float(np.mean(components, 0)[0]),
        waveform=float(np.mean(components, 0)[1]),
        duplicates=float(np.mean(components, 0)[2]),
        displacement=float(np.mean(components, 0)[3]),
        mean_abs_coefficient=float(np.mean(coefficients)),
        median_head_batch_ms=float(np.median(durations)),
        p95_head_batch_ms=float(np.percentile(durations, 95)),
        elapsed_seconds=time.perf_counter() - started,
        predictions=predictions,
        sources=returned_sources,
    )
